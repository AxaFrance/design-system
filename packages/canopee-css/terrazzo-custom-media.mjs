// Terrazzo plugin: writes the @custom-media of each target from the breakpoint
// primitives of the JSON. Names stay those of the current code, the value comes
// from the token, and the operator is always >= since the token holds the width
// where the breakpoint starts.

const toPx = (token) => {
  const v = token.$value
  if (!v || v.unit !== 'px') throw new Error(`${token.id}: px dimension expected`)
  return v.value
}

export default function customMedia({ targets }) {
  return {
    name: 'canopee-custom-media',
    build({ tokens, outputFile }) {
      for (const [targetName, { filename, media }] of Object.entries(targets)) {
        const lines = Object.entries(media).map(([name, id]) => {
          const token = tokens[id]
          if (!token) throw new Error(`${targetName}: --${name} refers to ${id}, missing from the JSON`)
          const px = toPx(token)
          return `@custom-media --${name} screen and (width >= ${px === 0 ? 0 : `${px}px`});`
        })
        outputFile(filename, `/* Generated by Terrazzo from the design tokens. Do not edit. */\n\n${lines.join('\n')}\n`)
      }
    }
  }
}
