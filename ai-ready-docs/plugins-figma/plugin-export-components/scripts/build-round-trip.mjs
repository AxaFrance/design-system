#!/usr/bin/env node
// Produces scripts/rebuild.bridge.js: the script to paste into a figma_execute to
// rebuild a component in Figma from its JSON alone (round trip test).
//
// Usage: node scripts/build-round-trip.mjs [--json path] [--step all|create|assemble|delete]
//                                           [--from 0] [--to 50] [--x 0 --y 0] [--output path]
//                                           [--file key] [--page name] [--name name]
//   --json    sheet to rebuild (default ai-ready-docs/b2c/composants/button/button.json)
//   --file    key of the only Figma file where the script agrees to write (default the
//             « DS IA ready » B2C branch, UWk4fT45i82ESNhGaAnj6p)
//   --page    page where it writes (default « Test - Components AI-ready »)
//   --name    name of the rebuilt set (default « Retour/ » followed by the component name)
//   --step    all (default), or create / assemble in several calls, or delete
//   --from, --to  range of variants created (create step)
//   --global-sheet  reads the sheet in globalThis.__ROUND_TRIP_SHEET instead of embedding it
//   --x, --y  position of the set on the page (otherwise under the content of the page)
// The expansion rules of the overrides are copied from src/code.ts. The types are removed with
// TypeScript (devDependency of the plugin): run npm ci first.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const option = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const json = resolve(
  option("--json") ||
    join(here, "..", "..", "..", "b2c", "composants", "button", "button.json"),
);
const output = resolve(option("--output") || join(here, "rebuild.bridge.js"));
const config = { step: option("--step") || "all" };
if (option("--from") !== undefined) config.from = Number(option("--from"));
if (option("--to") !== undefined) config.to = Number(option("--to"));
if (option("--file") !== undefined) config.file = option("--file");
if (option("--page") !== undefined) config.page = option("--page");
if (option("--name") !== undefined) config.name = option("--name");
if (option("--x") !== undefined) config.x = Number(option("--x"));
if (option("--y") !== undefined) config.y = Number(option("--y"));

// --global-sheet: the sheet is not copied into the script, it reads it in globalThis.__ROUND_TRIP_SHEET,
// set once by a figma_execute (useful when the sheet is too heavy to paste at each step).
const sheet = args.includes("--global-sheet")
  ? "globalThis.__ROUND_TRIP_SHEET"
  : JSON.stringify(JSON.parse(readFileSync(json, "utf8")));
const template = readFileSync(join(here, "rebuild.template.js"), "utf8");

// The format rules come from src/code.ts, between the markers START RULES and END RULES.
const START = "// >>> START RULES";
const END = "// <<< END RULES";
// src/code.ts without its types: the script pasted in figma_execute is plain JavaScript.
const code = ts.transpileModule(
  readFileSync(join(here, "..", "src", "code.ts"), "utf8"),
  {
    compilerOptions: {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.ESNext,
      removeComments: false,
    },
  },
).outputText;
const start = code.indexOf(START);
const end = code.indexOf(END);
if (start < 0 || end < start) {
  console.error(
    "Repères introuvables dans src/code.ts : " + START + " et " + END,
  );
  process.exit(1);
}
const rules = code.slice(start + START.length, end).trim();
const bridge =
  "// Generated by scripts/build-round-trip.mjs. Do not edit by hand.\n" +
  template
    .split("__RULES__")
    .join(rules)
    .split("__SHEET__")
    .join(sheet)
    .split("__CONFIG__")
    .join(JSON.stringify(config));

writeFileSync(output, bridge);
console.log(
  "Écrit : " +
    output +
    " (" +
    bridge.length +
    " caractères, étape " +
    config.step +
    ")",
);
