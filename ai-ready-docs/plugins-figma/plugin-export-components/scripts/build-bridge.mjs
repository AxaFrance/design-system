#!/usr/bin/env node
// Produces scripts/extract.bridge.js: the extraction core of src/code.ts, ready to be
// pasted as is into a figma_execute. It takes the id of a component set from a
// constant at the top and returns the JSON of the sheet.
//
// Usage: node scripts/build-bridge.mjs [--id 12:34] [--output path]
//   --id      id of the component set, written in the constant at the top (otherwise to replace by hand)
//   --output  file to write (default scripts/extract.bridge.js)
// The types are removed with TypeScript (devDependency of the plugin): run npm ci first.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const here = dirname(fileURLToPath(import.meta.url));
const START = "// >>> START EXTRACTION";
const END = "// <<< END EXTRACTION";

const args = process.argv.slice(2);
const option = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const id = option("--id") || "COMPONENT_SET_ID";
const output = resolve(option("--output") || join(here, "extract.bridge.js"));

// src/code.ts without its types: the script pasted in figma_execute is plain JavaScript.
const code = ts.transpileModule(
  readFileSync(join(here, "..", "src", "code.ts"), "utf8"),
  {
    compilerOptions: {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.ESNext,
      removeComments: false,
    },
  },
).outputText;
const start = code.indexOf(START);
const end = code.indexOf(END);
if (start < 0 || end < 0 || end < start) {
  console.error(
    "Repères introuvables dans src/code.ts : " + START + " et " + END,
  );
  process.exit(1);
}
const core = code.slice(start + START.length, end).trim();

const bridge = `// Generated by scripts/build-bridge.mjs from src/code.ts. Do not edit by hand.
// Paste as is into a figma_execute, after replacing the id below with the one of the
// component set (or of a single component). Returns the JSON of the sheet, as text.
const ID_COMPONENT_SET = ${JSON.stringify(id)}

${core}

const bridgeTarget = await figma.getNodeByIdAsync(ID_COMPONENT_SET)
if (!bridgeTarget) throw new Error('Aucun noeud pour l\\'id ' + ID_COMPONENT_SET)
if (bridgeTarget.type !== 'COMPONENT_SET' && bridgeTarget.type !== 'COMPONENT') throw new Error('Le noeud ' + ID_COMPONENT_SET + ' est de type ' + bridgeTarget.type + ' : il faut un component set ou un composant.')
return serialize(await extract(bridgeTarget))
`;

writeFileSync(output, bridge);
console.log("Écrit : " + output + " (" + bridge.length + " caractères)");
